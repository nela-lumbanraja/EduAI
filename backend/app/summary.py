"""Consolidated exam summary for the Pengawas.

One summary per exam, generated by the backend itself (maintenance loop, every 30 s), never by a
browser timer:
  * 'pre_end' when PRE_END_MIN minutes remain before the scheduled end
    (end = exams.date + start_time + duration_min, read from the database every check, so a changed
    schedule is picked up automatically until the summary exists);
  * 'final' at/after the scheduled end, or when the exam is set to "Selesai", if no 'pre_end' summary
    was made - e.g. monitoring started with less than PRE_END_MIN minutes left, or the exam was
    closed early.
The exam_summaries table has exam_id as PRIMARY KEY and rows are written with INSERT OR IGNORE, so a
backend restart, repeated checks or several dashboards can never create a second summary.

Only exams where AI monitoring was started at least once get a summary (nothing to summarise
otherwise). Counts come only from recorded indication events (one event = one qualifying episode;
overlapping events are merged, see cases.merge_episodes). "Cannot analyse" periods are reported
separately and never counted as behaviour. The summary lists potential indications for review; it
does not state that anyone cheated.
"""
import json
import logging
from datetime import datetime, timedelta, timezone
from typing import Optional

from . import cases as casing
from .db import now_iso

log = logging.getLogger("eduai.summary")
PRE_END_MIN = 10

# Behaviours from the product requirements that the AI cannot detect in this configuration. Listed in
# the summary so a missing count is not mistaken for "not observed". Filled by configure_detectors().
BOOK_OFF = {"behavior": "Buku/referensi tidak sah",
            "reason": "Indikator BOOK_VISIBLE dimatikan atau detektor objek tidak dimuat di konfigurasi AI.",
            "rule": "3 episode dalam 1 jam"}
UNSUPPORTED = [dict(BOOK_OFF)]


def configure_detectors(cfg: dict) -> list:
    """Book counts are only meaningful when BOOK_VISIBLE and the object detector are both enabled."""
    ind = (cfg or {}).get("indicators") or {}
    od = ((cfg or {}).get("models") or {}).get("object_detector") or {}
    book_on = bool((ind.get("BOOK_VISIBLE") or {}).get("enabled")) and od.get("enabled", True) is not False
    UNSUPPORTED.clear()
    if not book_on:
        UNSUPPORTED.append(dict(BOOK_OFF))
    return UNSUPPORTED


def _tz(name: str):
    if not name:
        return None
    try:
        from zoneinfo import ZoneInfo
        return ZoneInfo(name)
    except Exception:                                  # unknown name / no tz database (Windows: pip install tzdata)
        log.warning("EDUAI_TIMEZONE=%r not usable; using the server's local time", name)
        return None


def exam_window(exam: dict, tz_name: str = ""):
    """(start, end) as aware datetimes, or None when the schedule cannot be read."""
    try:
        naive = datetime.strptime(f"{exam['date']} {exam['start_time']}", "%Y-%m-%d %H:%M")
        minutes = int(exam["duration_min"])
    except (KeyError, TypeError, ValueError):
        return None
    if minutes <= 0:
        return None
    tz = _tz(tz_name)
    start = naive.replace(tzinfo=tz) if tz else naive.astimezone()      # naive = server local time
    return start, start + timedelta(minutes=minutes)


def _parse(iso: Optional[str]) -> Optional[datetime]:
    if not iso:
        return None
    d = datetime.fromisoformat(iso)
    return d if d.tzinfo else d.replace(tzinfo=timezone.utc)


def due_kind(exam: dict, now: datetime, tz_name: str = "") -> Optional[str]:
    """Which summary is due now ('pre_end' / 'final') or None. Does not look at existing summaries."""
    started = _parse(exam.get("monitoring_started_at"))
    if not started:
        return None                                    # AI monitoring never ran: nothing to summarise
    if exam["status"] == "Selesai":
        return "final"
    if exam["status"] != "Sedang Berlangsung":
        return None
    win = exam_window(exam, tz_name)
    if not win:
        return None                                    # no known end: only a final summary when closed
    end = win[1]
    if now >= end:
        return "final"
    trigger = end - timedelta(minutes=PRE_END_MIN)
    if now >= trigger:
        # monitoring started inside the last 10 minutes: wait for one final summary instead
        return "pre_end" if started <= trigger else None
    return None


def build(db, exam: dict, now: Optional[datetime] = None) -> dict:
    """Group every recorded indication by student and indicator (all enrolled students listed)."""
    now = now or datetime.now(timezone.utc)
    students = db.all("SELECT u.id, u.name, u.nis FROM exam_students es JOIN users u ON u.id=es.student_id"
                      " WHERE es.exam_id=? ORDER BY u.name", (exam["id"],))
    out = []
    for s in students:
        rows = db.all("SELECT * FROM events WHERE exam_id=? AND student_id=?", (exam["id"], s["id"]))
        ind = [r for r in rows if r["category"] == "indication"]
        bad = [r for r in rows if r["category"] == "cannot_analyze"]
        analysed = bool(rows) or bool(db.one("SELECT 1 FROM ai_status WHERE exam_id=? AND student_id=?",
                                             (exam["id"], s["id"])))
        items = []
        for group in casing.group_events(ind, 0, now):                     # one group per indicator
            c = casing.summarize(group, now)
            items.append({
                "indicator": c["indicator"], "label": c["label"], "case_id": c["case_id"],
                "occurrences": c["episode_count"], "events": c["event_count"],
                "first_ts": c["first_start_ts"], "last_ts": c["last_start_ts"], "last_end_ts": c["last_end_ts"],
                "episodes": [{"start_ts": e["start_ts"], "end_ts": e["end_ts"], "evidence_id": e["evidence_id"]}
                             for e in c["episodes"]],
                "evidence_count": c["evidence_count"], "unreviewed": c["unreviewed_count"],
                "rule": c["rule"]})
        items.sort(key=lambda i: (-i["occurrences"], i["indicator"]))
        bad_s = sum(max(0.0, ((_parse(r["end_ts"]) or now) - _parse(r["start_ts"])).total_seconds()) for r in bad)
        out.append({"student_id": s["id"], "name": s["name"], "nis": s["nis"],
                    "analysis": "analysed" if analysed else "no_data",
                    "cannot_analyze": {"periods": len(bad), "total_s": round(bad_s, 1)},
                    "indications": items,
                    "rules_met": sum(1 for i in items if i["rule"]["met"])})
    return {"exam_id": exam["id"], "exam_name": exam["name"], "generated_at": now.isoformat(timespec="milliseconds"),
            "students": out, "unsupported": UNSUPPORTED,
            "note": "Indikasi potensial untuk ditinjau pengawas, bukan bukti pelanggaran."}


def stored(db, exam_id: int) -> Optional[dict]:
    r = db.one("SELECT * FROM exam_summaries WHERE exam_id=?", (exam_id,))
    if not r:
        return None
    return {"exam_id": exam_id, "kind": r["kind"], "scheduled_end": r["scheduled_end"], "created_at": r["created_at"],
            "summary": json.loads(r["payload"])}


def generate(db, exam: dict, kind: str, now: Optional[datetime] = None, tz_name: str = "") -> bool:
    """Write the summary once. Returns True only for the call that actually created it."""
    if db.one("SELECT 1 FROM exam_summaries WHERE exam_id=?", (exam["id"],)):
        return False
    payload = build(db, exam, now)
    win = exam_window(exam, tz_name)
    # PRIMARY KEY + INSERT OR IGNORE: if another check got there first, nothing is written (0 rows).
    created = db.changes(
        "INSERT OR IGNORE INTO exam_summaries (exam_id, kind, scheduled_end, created_at, payload) VALUES (?,?,?,?,?)",
        (exam["id"], kind, win[1].isoformat() if win else None, now_iso(), json.dumps(payload))) == 1
    if created:
        log.info("exam %s: %s summary generated (%d students)", exam["id"], kind, len(payload["students"]))
    return created


def check_exam(db, exam: dict, now: Optional[datetime] = None, tz_name: str = "") -> Optional[str]:
    now = now or datetime.now(timezone.utc)
    kind = due_kind(exam, now, tz_name)
    if kind and generate(db, exam, kind, now, tz_name):
        return kind
    return None


def check_all(db, now: Optional[datetime] = None, tz_name: str = "") -> list:
    """Called by the backend maintenance loop. Returns [(exam_id, kind)] created in this call."""
    made = []
    for exam in db.all("SELECT * FROM exams WHERE monitoring_started_at IS NOT NULL"
                       " AND status IN ('Sedang Berlangsung','Selesai')"
                       " AND id NOT IN (SELECT exam_id FROM exam_summaries)"):
        kind = check_exam(db, exam, now, tz_name)
        if kind:
            made.append((exam["id"], kind))
    return made
